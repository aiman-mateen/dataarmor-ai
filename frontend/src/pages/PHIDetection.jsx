import React from "react";
import { ChevronDown, Lock, Upload } from "lucide-react";
import Card from "../components/ui/Card";
import Badge from "../components/ui/Badge";
import Button from "../components/ui/Button";
import ProgressBar from "../components/ui/ProgressBar";
import PageHeader from "../components/ui/PageHeader";
import { CLASS_OPTIONS } from "../constants/theme";

export default function PHIDetection({ go, overrides, setOverrides, apiResult }) {

  const rows = apiResult
    ? Object.entries(apiResult.predictions).map(([col, cls]) => ({
        col,
        cls,
        conf: apiResult.confidence_scores?.[col] ?? 85,
      }))
    : null;

  if (!rows) {
    return (
      <div>
        <PageHeader
          title="PHI Detection Results"
          description="Upload a dataset first to see PHI detection results."
        />
        <Card className="p-10 flex flex-col items-center text-center">
          <div className="w-12 h-12 rounded-full bg-slate-100 flex items-center justify-center mb-4">
            <Upload className="w-5 h-5 text-slate-400" />
          </div>
          <p className="text-sm font-medium text-slate-700">No dataset uploaded yet</p>
          <p className="text-sm text-slate-500 mt-1 mb-5">
            Upload a CSV file to run PHI detection across the six-model ensemble.
          </p>
          <Button variant="primary" onClick={() => go("upload")}>
            Upload Dataset
          </Button>
        </Card>
      </div>
    );
  }

  return (
    <div>
      <PageHeader
        title="PHI Detection Results"
        description="Predictions generated by the DataArmor AI six-model ensemble classifier."
      />

      <Card className="overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead className="sticky top-0 bg-slate-50 border-b border-slate-200">
              <tr>
                {["Column Name", "Predicted Class", "Confidence Score", "Override Classification"].map((h) => (
                  <th key={h} className="text-left font-medium text-slate-500 px-6 py-3 text-xs uppercase tracking-wide">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {rows.map((row, i) => (
                <tr
                  key={row.col}
                  className={`${i % 2 === 0 ? "bg-white" : "bg-slate-50/60"} hover:bg-teal-50/50 transition-colors border-b border-slate-100 last:border-0`}
                >
                  <td className="px-6 py-3.5 font-medium text-slate-700 font-mono text-[13px]">{row.col}</td>
                  <td className="px-6 py-3.5">
                    <Badge cls={overrides[row.col] || row.cls} />
                  </td>
                  <td className="px-6 py-3.5">
                    <div className="flex flex-col gap-1 w-44">
                      <div className="flex items-center justify-between mb-1">
                        <span className={`text-sm font-semibold ${
                          row.conf >= 80
                            ? "text-teal-600"
                            : row.conf >= 60
                            ? "text-amber-500"
                            : "text-red-500"
                        }`}>
                          {row.conf}%
                        </span>
                        {row.conf < 60 && (
                          <span className="text-[10px] text-red-400 font-medium uppercase tracking-wide">
                            Review
                          </span>
                        )}
                        {row.conf >= 60 && row.conf < 80 && (
                          <span className="text-[10px] text-amber-400 font-medium uppercase tracking-wide">
                            Moderate
                          </span>
                        )}
                        {row.conf >= 80 && (
                          <span className="text-[10px] text-teal-400 font-medium uppercase tracking-wide">
                            High
                          </span>
                        )}
                      </div>
                      <div className="w-full bg-slate-100 rounded-full h-1.5">
                        <div
                          className={`h-1.5 rounded-full transition-all ${
                            row.conf >= 80
                              ? "bg-teal-500"
                              : row.conf >= 60
                              ? "bg-amber-400"
                              : "bg-red-400"
                          }`}
                          style={{ width: `${row.conf}%` }}
                        />
                      </div>
                    </div>
                  </td>
                  <td className="px-6 py-3.5">
                    <div className="relative inline-block">
                      <select
                        value={overrides[row.col] || row.cls}
                        onChange={(e) => setOverrides({ ...overrides, [row.col]: e.target.value })}
                        className="appearance-none text-sm border border-slate-300 rounded-lg pl-3 pr-8 py-1.5 bg-white text-slate-700 focus:outline-none focus:ring-2 focus:ring-teal-500/30 focus:border-teal-500 cursor-pointer"
                      >
                        {CLASS_OPTIONS.map((c) => (
                          <option key={c} value={c}>
                            {c}
                          </option>
                        ))}
                      </select>
                      <ChevronDown className="w-3.5 h-3.5 text-slate-400 absolute right-2.5 top-1/2 -translate-y-1/2 pointer-events-none" />
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>

      <div className="flex justify-end mt-6">
        <Button variant="primary" onClick={() => go("anonymization")}>
          <Lock className="w-4 h-4" /> Proceed to Anonymization
        </Button>
      </div>
    </div>
  );
}